        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_TaiSanTra_tinhTrang CHECK (CHAR_LENGTH(TRIM(tinhTrangTra)) BETWEEN 1 AND 255)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_ci;

CREATE TABLE tblLoi (
    id BIGINT NOT NULL AUTO_INCREMENT,
    ten VARCHAR(255) NOT NULL,
    moTa VARCHAR(500) NOT NULL,
    tienPhat DECIMAL(12,0) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT ck_Loi_ten CHECK (CHAR_LENGTH(TRIM(ten)) BETWEEN 1 AND 255),
    CONSTRAINT ck_Loi_moTa CHECK (CHAR_LENGTH(TRIM(moTa)) BETWEEN 1 AND 500),
    CONSTRAINT ck_Loi_tienPhat CHECK (tienPhat BETWEEN 0 AND 999999999999)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_ci;

CREATE TABLE tblLoiMuon (
    id BIGINT NOT NULL AUTO_INCREMENT,
    chiTietMuonId BIGINT NOT NULL,
    loiId BIGINT NOT NULL,
    ten VARCHAR(255) NOT NULL,
    moTa VARCHAR(500) NOT NULL,
    PRIMARY KEY (id),
    KEY ix_LoiMuon_chiTiet (chiTietMuonId),
    CONSTRAINT uq_LoiMuon_loi UNIQUE (chiTietMuonId, loiId),
    CONSTRAINT fk_LoiMuon_ChiTietMuon FOREIGN KEY (chiTietMuonId) REFERENCES tblChiTietMuon (id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_LoiMuon_Loi FOREIGN KEY (loiId) REFERENCES tblLoi (id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_LoiMuon_ten CHECK (CHAR_LENGTH(TRIM(ten)) BETWEEN 1 AND 255),
    CONSTRAINT ck_LoiMuon_moTa CHECK (CHAR_LENGTH(TRIM(moTa)) BETWEEN 1 AND 500)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_ci;

