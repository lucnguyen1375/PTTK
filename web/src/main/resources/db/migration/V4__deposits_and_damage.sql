CREATE TABLE tblTaiSanCoc (
    id BIGINT NOT NULL AUTO_INCREMENT,
    moTa VARCHAR(500) NOT NULL,
    giaTriUocTinh DECIMAL(12,0) NOT NULL,
    ten VARCHAR(255) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT ck_TaiSanCoc_moTa CHECK (CHAR_LENGTH(TRIM(moTa)) BETWEEN 1 AND 500),
    CONSTRAINT ck_TaiSanCoc_ten CHECK (CHAR_LENGTH(TRIM(ten)) BETWEEN 1 AND 255),
    CONSTRAINT ck_TaiSanCoc_gia CHECK (giaTriUocTinh BETWEEN 0 AND 999999999999)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_ci;

CREATE TABLE tblCTTaiSanCoc (
    id BIGINT NOT NULL AUTO_INCREMENT,
    giaTri DECIMAL(12,0) NOT NULL,
    tinhTrang VARCHAR(255) NOT NULL,
    daTra BOOLEAN NOT NULL DEFAULT FALSE,
    taiSanCocId BIGINT NOT NULL,
    phieuMuonId BIGINT NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_CTTaiSanCoc_TaiSanCoc FOREIGN KEY (taiSanCocId) REFERENCES tblTaiSanCoc (id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_CTTaiSanCoc_PhieuMuon FOREIGN KEY (phieuMuonId) REFERENCES tblPhieuMuon (id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_CTTaiSanCoc_gia CHECK (giaTri BETWEEN 0 AND 999999999999),
    CONSTRAINT ck_CTTaiSanCoc_tinhTrang CHECK (CHAR_LENGTH(TRIM(tinhTrang)) BETWEEN 1 AND 255)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_ci;

CREATE TABLE tblTaiSanTra (
    ctTaiSanCocId BIGINT NOT NULL,
    hoaDonTraId BIGINT NOT NULL,
    ngayTra DATE NOT NULL,
    tinhTrangTra VARCHAR(255) NOT NULL,
    PRIMARY KEY (ctTaiSanCocId),
    KEY ix_TaiSanTra_hoaDon (hoaDonTraId),
    CONSTRAINT fk_TaiSanTra_CTTaiSanCoc FOREIGN KEY (ctTaiSanCocId) REFERENCES tblCTTaiSanCoc (id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
